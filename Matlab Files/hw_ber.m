phi = linspace(-0.35,15.39,length(TX)); % phase (example)

%% ================== BUILD H(Ω) ==================
lambda = lambda_nm*1e-9;
omega  = 2*pi*c./lambda;
[omega,idx] = sort(omega);

H = TX(idx).*exp(1j*phi(idx));
Omega = omega - omega0;

%% ================== SIMULATION ==================
totalErr = 0;
totalBits = 0;

EYE_BUF = [];
EYE_CAPTURED = false;
Neye = 200;

for blk = 1:Nblk

    [bits,~] = PRBS_generator(1,PRBS_order,1);
    txBits = bits(1,:);

    % TX waveform
    I_tx = conv(repelem(txBits,Ns),hRC,'full');
    I_tx = I_tx/max(I_tx);
    I_tx(I_tx<0)=0;

    % Laser envelope
    [A_laser,~] = laserCW(LASER,Fs,length(I_tx));
    E = sqrt(P0*I_tx).*A_laser;

    % --- SWITCH ---
    N = length(E);
    f = (-N/2:N/2-1)*(Fs/N);
    Omega_fft = 2*pi*f;
    Hsw = interp1(Omega,H,Omega_fft,'linear',0);
    Hsw = fftshift(Hsw);

    E = ifft(fft(E).*Hsw);

    % Photodiode
    [io,~] = photodiode_PD(E,Fs,PD);
    v = filtfilt(b,a,io*PD.RL);

    % Sampling
    idx0 = gd + Ns/2;
    sym = v(idx0:Ns:idx0+(Nbit-1)*Ns);

    % AGC
    A1 = mean(sym(txBits==1));
    A0 = mean(sym(txBits==0));
    v = v/(A1-A0);

    if ~EYE_CAPTURED
        EYE_BUF = v(idx0:idx0+Neye*Ns-1);
        EYE_CAPTURED = true;
    end

    rx = sym > mean(sym);
    totalErr  = totalErr + sum(rx~=txBits);
    totalBits = totalBits + Nbit;
end

BER = totalErr/totalBits;

fprintf('BER = %.3e after %d blocks\n',BER,Nblk);

%% ================== EYE =========================
figure('Color','w');
