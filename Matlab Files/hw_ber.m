%% ================== CONSTANTS ==================
c = 3e8;

%% ================== SYSTEM =====================
Rb   = 25e9;                 % 10 Gbps
Ns   = 32;                   % samples/symbol
Fs   = Rb * Ns;
Nblk = 1000;                  % number of blocks
PRBS_order = 11;
Nbit = 2^PRBS_order - 1;

lambda0 = 1550e-9;
omega0  = 2*pi*c/lambda0;

%% ================== TX FILTER ==================
rollOff = 0.3;
span = 10;
hRC = rcosdesign(rollOff, span, Ns, 'normal');
gd = (length(hRC)-1)/2;

%% ================== LASER ======================
LASER.linewidth = 1e6;
LASER.RIN_dB    = -150;
LASER.phase0    = 0;

P_dBm = -5;
P0 = 10^((P_dBm-30)/10);

%% ================== PHOTODIODE =================
PD.R  = 0.9;
PD.RL = 1e4;
PD.BW = 0.35*Rb;
PD.T  = 310;

%% ================== RX FILTER ==================
BW_rx = 0.75*Rb;
[b,a] = butter(4, BW_rx/(Fs/2));

