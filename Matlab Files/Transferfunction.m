%% ===================== BUILD H(ω) =====================
c = 3e8;
lambda = lambda_nm * 1e-9;
omega = 2*pi*c ./ lambda;

[omega, idx] = sort(omega);
TX  = TX(idx);
phi = phi(idx);

H = TX .* exp(1j*phi);

% Parameters for the laser source
laser_lambda = 1550e-9; % Laser wavelength in meters
laser_omega = 2 * pi * c / laser_lambda; % Laser angular frequency

% Bitrate and sequence length
bitrate = 10e9; % 10 Gbps
sequence_length = 100; % Number of samples
time = (0:sequence_length-1) / bitrate; % Time vector

% Random Sequence
Random_signal = randi([0, 1], 1, sequence_length);

% Modulate the random signal to optical signal
modulated_signal = Random_signal .* exp(1j * laser_omega * time);

% Compute the spectrum of the modulated signal
spectrum = fft(modulated_signal);

% Multiply by H(ω)
spectrum_filtered = spectrum .* H(1:length(spectrum));

% Take IFFT to get the time domain signal back
filtered_signal = ifft(spectrum_filtered);

% Plot the random signal
figure;
subplot(3, 1, 1);
plot(time, Random_signal);
title('Random Signal');
xlabel('Time (s)');
ylabel('Amplitude');

% Plot the spectrum
frequencies = linspace(0, c/(2 * laser_lambda), length(spectrum)/2);
subplot(3, 1, 2);
plot(frequencies, abs(spectrum(1:length(frequencies))));
title('Spectrum of Modulated Signal');
xlabel('Frequency (Hz)');
ylabel('Magnitude');

% Plot the filtered time domain signal
subplot(3, 1, 3);
plot(time, real(filtered_signal));
title('Filtered Time Domain Signal');
xlabel('Time (s)');
ylabel('Amplitude');